// The split that decision draws:
//
//   後端（analysis-ts, GET /metrics）  formulaLatex、unit、期別、sources、referenceUrl、
//                                      academicSourceUrl、badge.threshold 與其出處
//   前端（this file）                  定義、什麼時候不適用、容易誤讀的地方
//
// WHY the prose moved, when everything else here reads from the backend on principle: it is the
// only part of a metric's record that is WRITING rather than DATA, and its audience is this app's
// audience, not a generic API consumer. The backend copy was written by an analyst for an analyst
// and reads that way. Measured examples from the version this file replaces, all user-facing:
//
//   「近三年一季都沒賺錢的公司分母沒有意義，記為 null」   ← a database word, in prose for retirees
//   「本站以百分比儲存（100% 代表…）」                    ← a storage detail
//   「股價用財報公告日（knowledge date）當天…」            ← an English implementation term
//   「研發費用只存在 XBRL 損益表寬表」                      ← a table shape
//   「要搭配利息保障倍數與淨負債對 EBITDA 看」              ← jargon explained with more jargon
//   deRatio's 限制: one sentence, four semicolons, ~150 characters, no break
//
// 「本站…」also appears throughout it, which analysis-ts's own compliance wording rule rejects —
// we collect and organise other people's definitions, we don't author thresholds（投顧法規考量）.
//
// WHAT DID NOT MOVE, and must not: every substantive fact and every citation. The backend copy is
// excellent material（「營建業預收工程款、便利商店應付帳款週轉都會把比率推高」,「15% 是巴菲特 1987
// 年致股東信裡的單年門檻」）and the「金融業不適用」warnings are correctness-grade, not style. This
// is a re-registering and a re-paragraphing of that material, never a rewrite of its substance.
//
// THE DRIFT GUARD is the whole reason this is safe. Prose in a different service from the formula
// it describes can silently rot: analysis-ts revised `sue` on 2026-09-22（formulaVersion 3, drift
// term removed, whole market recomputed）, and copy living here would have gone on describing a
// formula that no longer existed with nothing failing. So every entry pins the `formulaLatex` +
// `unit` it was written against, as a short hash; scripts/check-metric-copy-drift.mjs recomputes
// that hash from the live catalog and fails when it moves. A formula revision therefore FORCES a
// copy review instead of rotting. Regenerate a pin only after re-reading the affected copy.
//
// A metric with no entry here falls back to the backend's own three fields, so this file can grow
// one metric at a time and no page ever loses a section.
