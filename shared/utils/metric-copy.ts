// 指標說明文案 — owned by the frontend since 2026-09-22, by direct decision:「越接近數學 越專業的
// 我想放在後端，一方面統一全站計算方式，一方面開發時可以參照。但是這些體量較大的文案真的是給退休族
// 用的…所以這個部分的文案我想改為放在前端。」
//
// The split that decision draws:
//
//   後端（analysis-ts, GET /metrics）  formulaLatex、unit、期別、sources、referenceUrl、
//                                      academicSourceUrl、badge.threshold 與其出處
//   前端（this file）                  定義、什麼時候不適用、容易誤讀的地方
//
// WHY the prose moved, when everything else here reads from the backend on principle: it is the
// only part of a metric's record that is WRITING rather than DATA, and its audience is this app's
// audience, not a generic API consumer. The backend copy was written by an analyst for an analyst
// and reads that way. Measured examples from the version this file replaces, all user-facing:
//
//   「近三年一季都沒賺錢的公司分母沒有意義，記為 null」   ← a database word, in prose for retirees
//   「本站以百分比儲存（100% 代表…）」                    ← a storage detail
//   「股價用財報公告日（knowledge date）當天…」            ← an English implementation term
//   「研發費用只存在 XBRL 損益表寬表」                      ← a table shape
//   「要搭配利息保障倍數與淨負債對 EBITDA 看」              ← jargon explained with more jargon
//   deRatio's 限制: one sentence, four semicolons, ~150 characters, no break
//
// 「本站…」also appears throughout it, which analysis-ts's own compliance wording rule rejects —
// we collect and organise other people's definitions, we don't author thresholds（投顧法規考量）.
//
// WHAT DID NOT MOVE, and must not: every substantive fact and every citation. The backend copy is
// excellent material（「營建業預收工程款、便利商店應付帳款週轉都會把比率推高」,「15% 是巴菲特 1987
// 年致股東信裡的單年門檻」）and the「金融業不適用」warnings are correctness-grade, not style. This
// is a re-registering and a re-paragraphing of that material, never a rewrite of its substance.
//
// THE DRIFT GUARD is the whole reason this is safe. Prose in a different service from the formula
// it describes can silently rot: analysis-ts revised `sue` on 2026-09-22（formulaVersion 3, drift
// term removed, whole market recomputed）, and copy living here would have gone on describing a
// formula that no longer existed with nothing failing. So every entry pins a short hash of the
// maths contract it was written against; scripts/check-metric-copy-drift.mjs recomputes that hash
// from the live catalog and fails when it moves. A formula revision therefore FORCES a copy review
// instead of rotting. Regenerate a pin only after re-reading the affected copy — a pin refreshed
// blind silences the one thing that would have caught it.
//
// It has already earned that: ROE's denominator changed from period-end equity to an average the
// day after this file shipped, and the guard stopped the four copy lines describing the old
// behaviour from going stale.
//
// A metric with no entry here falls back to the backend's own three fields, so this file can grow
// one metric at a time and no page ever loses a section.
export interface MetricCopy {
  // The metric's maths contract as it stood when this copy was written — formulaVersion,
  // formulaLatex, unit and periods, hashed. check-metric-copy-drift.mjs owns the exact recipe and
  // the reasoning for each input; regenerate a pin only from that script, never by hand.
  pin: string
  // definition／limitations／misreadings 是**選填**（2026-09-26）。原本三個都必填，代表想加
  // 「怎麼看」就得連定義與限制一起搬到前端——但那三段後端已經有、而且是照本站規格寫的（營運周轉那六
  // 支，analysis-ts 1b7bcc8e），複製一份過來正是本檔 drift guard 存在要防的事：同一段文字兩個家。
  //
  // 所以分工再細一層：**reading 永遠是前端的**（它是讀法指導，不是定義），其餘三段只在我們真的改寫過
  // 的時候才出現在這裡，沒改寫就留空、由 StockMetricDetailPage 回退到後端那三個欄位。
  definition?: string
  // 「這個數字要怎麼看」（2026-09-26「每個指標都要模板化的指導要怎麼看…以應付帳款付現天數來說，這是
  // 我可以欠錢不還嗎還是甚麼？」）。既有三個欄位少的正是這一段：definition 說它是什麼，limitations
  // 說什麼時候別看，misreadings 糾正常見的錯——都沒有正面告訴讀者「數字動了代表發生什麼事」。
  //
  // 刻意做成三格而不是一段自由文字：自由文字會退化成「越高越好」這種話，而三格逼每一則都寫成**機械
  // 性的因果**（變大代表什麼「發生了」），寫不出評價句。這同時是法遵上的線——我們描述數字的動向，不
  // 替讀者判斷好壞（投顧法規考量，跟本檔案開頭「不授權門檻」同一條）。
  //
  // 必填，不是選填：設成必填之後 TypeScript 會擋住漏寫的條目，不必另外寫檢查腳本。
  reading: {
    // 數字變大代表發生了什麼。兩個方向都要給至少一個不帶價值判斷的可能原因。
    up: string
    // 數字變小代表發生了什麼。
    down: string
    // 跟誰比才有意義（自己的過去、同業、還是都不適合），以及為什麼。
    compare: string
  }
  limitations?: string[]
  misreadings?: string[]
}

